\getenv app_password POSTGRES_APP_PASSWORD

SELECT 'CREATE ROLE followw_app'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'followw_app')
\gexec
ALTER ROLE followw_app LOGIN PASSWORD :'app_password';

GRANT USAGE ON SCHEMA public TO followw_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO followw_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO followw_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO followw_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE ON SEQUENCES TO followw_app;
